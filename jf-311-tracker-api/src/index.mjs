const makeChecklistHtml = (issuesNotes, title, subtitle) => {
  const checklistSections = issuesNotes
    .map((answer) => {
      if (answer.type === "issues") {
        const listItems = answer.value
          .map((issue) => {
            return `<li>
            <label>
                <input type="checkbox">
                ${issue}
            </label>
          </li>`;
          })
          .join("");
        return `<h2>${answer.section}</h2><ul>${listItems}</ul>`;
      } else {
        return `<h3>${answer.section}</h3><p>${answer.value}</p>`;
      }
    })
    .join("");

  const htmlText = `<!DOCTYPE html>
    <html lang="en">
    <head>
        <meta charset="UTF-8">
        <meta name="viewport" content="width=device-width, initial-scale=1.0">
        <title>${title}</title>
        <link rel="stylesheet" href="https://justfix-311-checklists.s3.us-east-1.amazonaws.com/checklist-styles-upt.css">
    </head>
    <body>
        <h1>${title}</h1>
        <h2>${subtitle}</h2>
        ${checklistSections}
    </body>
    </html>`;

  return htmlText;
};

export const uploadChecklist = async (
  issuesNotes,
  s3Client,
  title,
  subtitle,
  subdir,
  hash,
) => {
  const checklistHtml = makeChecklistHtml(issuesNotes, title, subtitle);
  const bucket = process.env.CHECKLIST_BUCKET;
  const key = `${subdir}/${hash}/checklist.html`;
  const params = {
    Bucket: bucket,
    Key: key,
    Body: checklistHtml,
    ContentType: "text/html",
    ContentDisposition: "inline",
  };
  const command = new PutObjectCommand(params);
  await s3Client.send(command);

  return `https://${bucket}.s3.us-east-1.amazonaws.com/${key}`;
};

const updateChecklists = async (s3Client) => {
  const users = await getAllUsers();
  const checklistPromises = users.map(async (user) => {
    const title = "UPT 311 Checklist";
    const subtitle = `${user.address} - Apt ${user.apartment}`;
    return uploadChecklist(
      user.issuesNotes,
      s3Client,
      title,
      subtitle,
      "upt",
      user.id,
    );
  });
  await Promise.all(checklistPromises);

  const dbUpdatePromises = users.map(async (user) => {
    const params = {
      TableName: process.env.DB_TABLE,
      Key: {
        id: user.id,
      },
      UpdateExpression: "set checklistUrl = :c",
      ExpressionAttributeValues: {
        ":c": `https://${process.env.CHECKLIST_BUCKET}.s3.us-east-1.amazonaws.com/upt/${user.id}/checklist.html`,
      },
    };

    try {
      const resp = await ddbDocClient.send(new UpdateCommand(params));
      console.log("UpdateItem succeeded:", resp);
    } catch (err) {
      console.error("Unable to update item. Error:", err);
    }
  });
  await Promise.all(dbUpdatePromises);
};

export const handler = async (event) => {
  console.log("EVENT: ", JSON.stringify(event, null, 2));

  const { httpMethod, resource, action } = event;

  try {
    let response;

    if (action === "updateChecklists") {
      try {
        await updateChecklists(s3Client);
        await updateTypeformResponses();
      } catch (err) {
        console.error("checklists update failed", error);
      }
      response = {
        statusCode: 200,
        body: "Checklists regenerated on S3 and updated in DB",
      };
    } else if (action === "updateUptSheets") {
      // Eventbridge schedule
      try {
        await updateTypeformResponses();
      } catch (err) {
        console.error("typeform sheet update failed", error);
      }
      try {
        await updateViolations();
      } catch (err) {
        console.error("violations sheet update failed", error);
      }
      response = {
        statusCode: 200,
        body: "UPT Google Sheet updated",
      };
    } else if (httpMethod === "POST" && resource === "/srNumbers") {
      response = await addSrNumbersForUser(event);
    } else if (httpMethod === "GET" && resource === "/complaints/{id}") {
      response = await getUserComplaints(event);
    } else {
      response = {
        statusCode: 404,
        body: "Resource does not exist",
      };
    }

    return response;
  } catch (error) {
    console.error("ERROR: ", error);
    throw error; // Terminate function if secret cannot be retrieved
  }
};
