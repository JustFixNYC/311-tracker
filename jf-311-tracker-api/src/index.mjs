/**
 * Scans the DynamoDB table and retrieves all items, handling pagination automatically.
 * @returns {Promise<Array>} A promise that resolves to an array of all items.
 */
const getAllUsers = async () => {
  const allItems = [];
  let exclusiveStartKey = undefined;

  do {
    const scanParams = {
      TableName: process.env.DB_TABLE,
      ExclusiveStartKey: exclusiveStartKey,
    };

    try {
      const command = new ScanCommand(scanParams);
      const response = await ddbDocClient.send(command);

      // 3. Collect the items and check for more results
      if (response.Items) {
        allItems.push(...response.Items);
      }
      exclusiveStartKey = response.LastEvaluatedKey; // Update the start key for the next iteration
    } catch (error) {
      console.error("Error scanning DynamoDB table:", error);
      throw error;
    }
  } while (exclusiveStartKey); // Continue as long as there is a LastEvaluatedKey

  return allItems;
};

