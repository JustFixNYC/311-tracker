const updateGoogleSheets = async (rows, sheetId, addFitler = true) => {
  try {
    const doc = new GoogleSpreadsheet(
      process.env.GOOGLE_SPREADSHEET_ID,
      serviceAccountAuth,
      {
        retryConfig: {
          limit: 5,
          backoffLimit: 3000,
        },
      },
    );
    await doc.loadInfo(); // loads document properties and worksheets
    const sheet = doc.sheetsById[sheetId];
    await sheet.clearRows({ start: 0 }); // includes header
    const headerValues = Object.keys(rows[0]);
    await sheet.setHeaderRow(headerValues);
    await sheet.addRows(rows);
    if (addFitler) {
      const filter = {
        range: {
          startRowIndex: 0,
          endRowIndex: rows.length + 1,
          startColumnIndex: 0,
          endColumnIndex: Object.keys(rows[0]).length,
        },
      };
      await sheet.setBasicFilter(filter);
    }
    return sheet;
  } catch (err) {
    console.log("error updatinge google sheet:", err);
  }
};

