const updateViolations = async () => {
  const sql = `
    SELECT
    buildingid AS "HPD Building ID", 
    housenumber || ' ' || streetname || ' '|| borough AS "Address", 
    'https://hpdonline.nyc.gov/hpdonline/building/' || buildingid AS "HPD Online",
    apartment AS "Apartment",
    TO_CHAR(inspectiondate, 'YYY-MM-DD') AS "Inspection Date", 
    TO_CHAR(novissueddate, 'YYY-MM-DD') AS "Violation Issued", 
    violationstatus AS "Status",
    currentstatus AS "Current Status",
    TO_CHAR(currentstatusdate, 'YYY-MM-DD') "Current Status Date", 
    novdescription AS "Violation Description"
  FROM pinnacle_buildingids
  INNER JOIN hpd_violations USING(buildingid)
  WHERE inspectiondate > '${VIOLATIONS_START_DATE}'
  ORDER BY inspectiondate DESC;
  `;
  const result = await nycdbPool.query(sql);
  await updateGoogleSheets(result.rows, process.env.GOOGLE_VIOLATIONS_SHEET_ID);
  return;
};

